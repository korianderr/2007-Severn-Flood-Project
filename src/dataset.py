"""
dataset.py

Wraps the synthetic
scenarios generated by generate_scenarios.py (a DEM elevation grid + a range
of boundary WSEs, each with a saved depth grid) into the (input, target)
tensor pairs PyTorch's DataLoader expects during training.

Each item stacks two channels into one input tensor — elevation (constant
per dataset) and boundary_wse (broadcast to a full grid, since a CNN expects
every input to be shaped like a grid, not a lone scalar) — paired against
that scenario's saved depth grid as the target.
"""

from pathlib import Path
import random 
import numpy as np
import torch
from torch.utils.data import Dataset


def split_manifest(rows, n_train, n_val):
    random.shuffle(rows)

    train_rows = rows[0:n_train]
    val_rows = rows[n_train:n_val + n_train]
    test_rows = rows[n_val + n_train:len(rows)]

    return train_rows, val_rows, test_rows


class FloodDataset(Dataset):
    """
    One instance represents one split (train, val, or test) of the 25
    generated scenarios — never a mix, to avoid leaking pixels from the same
    scenario across splits (see project discussion on data leakage).

    Args:
        z: DEM elevation array, shape (H, W). Same for every scenario in
            this project (one fixed terrain, only boundary_wse varies).
        scenario_dir: directory containing the saved scenario .npy files
            (as written by generate_scenarios.py).
        manifest_rows: this split's slice of manifest.csv rows only — each
            row a dict-like object with 'boundary_wse' and 'filename' keys.
    """
    def __init__(self, z, scenario_dir, manifest_rows):
        self.z = z
        self.scenario_dir = scenario_dir
        self.rows = manifest_rows

    def __len__(self):
        """Number of scenarios in this split."""
        return len(self.rows)

    def __getitem__(self, i):
        """
        Build one (input, target) training pair for scenario i.

        Returns:
            input_tensor: shape (2, H, W) — elevation and broadcast
                boundary_wse stacked as channels.
            target_tensor: shape (1, H, W) — the true depth grid for this
                scenario's boundary_wse.
        """
        row = self.rows[i]
        boundary_wse = float(row['boundary_wse'])
        filename = row['filename']

        depth = np.load(Path(self.scenario_dir) / filename)

        wse_channel = np.full_like(self.z, boundary_wse, dtype=np.float32)
        input_array = np.stack([self.z, wse_channel], axis=0)  # shape (2, H, W)

        input_tensor = torch.from_numpy(input_array).float()
        target_tensor = torch.from_numpy(depth).float().unsqueeze(0)  # shape (1, H, W)

        return input_tensor, target_tensor
