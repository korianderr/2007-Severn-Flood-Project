"""
dataset.py

Wraps the synthetic
scenarios generated by generate_scenarios.py (a DEM elevation grid + a range
of boundary WSEs, each with a saved depth grid) into the (input, target)
tensor pairs PyTorch's DataLoader expects during training.

Each item stacks two channels into one input tensor — elevation (constant
per dataset) and boundary_wse (broadcast to a full grid, since a CNN expects
every input to be shaped like a grid, not a lone scalar) — paired against
that scenario's saved depth grid as the target.
"""

from pathlib import Path
import random
import numpy as np
import rasterio 
import csv
import torch
from torch.utils.data import Dataset, DataLoader


def split_manifest(rows, n_train, n_val, seed=42):
    """
    Shuffles rows given to ensure random severity for fairness in training, validation,
    and testing. Split into their seperate arrays and returned. 
    """
    by_wse = sorted(rows, key=lambda r: float(r['boundary_wse']))
    lowest, highest = by_wse[0], by_wse[-1]
    middle = by_wse[1:-1]

    random.Random(seed).shuffle(middle)

    train_rows = [lowest, highest] + middle[:n_train - 2]
    val_rows = middle[n_train - 2:n_train - 2 + n_val]
    test_rows = middle[n_train - 2 + n_val:]

    return train_rows, val_rows, test_rows


def normalise(array, min_val, max_val):
    """ 
    Rescale an array to roughly 0-1 using min-max scaling, so elevation
    (hundreds of metres), boundary_wse (low tens), and depth (a few
    metres) are all on a comparable scale before hitting the network.

    min_val/max_val must come from the training split only, and be reused
    unchanged for validation/test data - recomputing them separately per
    split would mean each split is scaled differently, making the
    numbers no longer comparable across splits.
    """
    return (array - min_val) / (max_val - min_val)


def load_datasets(dem_path="data/reach_clip_25m.tif",
                   manifest_path="data/scenarios/manifest.csv",
                   scenario_dir="data/scenarios"):
    """
    Loads the DEM and manifest, splits into train/val/test, computes
    normalisation min/max from the training split, and returns all
    three FloodDataset instances ready for use.

    Returns:
        (train_dataset, val_dataset, test_dataset)
    """
    with rasterio.open(dem_path) as src:
        z = src.read(1)

    # Pixels far above any trained WSE are irrelevant to flood behaviour
    # excluded from loss/CSI via mask rather than cropped.
    max_wse = 14.0
    margin = 5.0
    flood_mask = z <= (max_wse + margin)


    with open(manifest_path, newline="") as f:
        reader = csv.DictReader(f)
        rows = list(reader)

    train_rows, val_rows, test_rows = split_manifest(rows, n_train=70, n_val=15)

    z_min, z_max = float(z.min()), float(z.max())

    train_wses = [float(row['boundary_wse']) for row in train_rows]
    wse_min, wse_max = min(train_wses), max(train_wses)

    depth_min, depth_max = float('inf'), float('-inf')
    for row in train_rows:
        depth = np.load(Path(scenario_dir) / row['filename'])
        depth_min = min(depth_min, float(depth.min()))
        depth_max = max(depth_max, float(depth.max()))

    args = (z, scenario_dir, z_min, z_max, wse_min, wse_max, depth_min, depth_max)
    train_dataset = FloodDataset(*args[:1], args[1], train_rows, *args[2:], flood_mask)
    val_dataset = FloodDataset(*args[:1], args[1], val_rows, *args[2:], flood_mask)
    test_dataset = FloodDataset(*args[:1], args[1], test_rows, *args[2:], flood_mask)

    return train_dataset, val_dataset, test_dataset


class FloodDataset(Dataset):
    """
    One instance represents one split (train, val, or test) of the 25
    generated scenarios — never a mix, to avoid leaking pixels from the same
    scenario across splits (see project discussion on data leakage).

    Args:
        z: DEM elevation array, shape (H, W). Same for every scenario in
            this project (one fixed terrain, only boundary_wse varies).
        scenario_dir: directory containing the saved scenario .npy files
            (as written by generate_scenarios.py).
        manifest_rows: this split's slice of manifest.csv rows only — each
            row a dict-like object with 'boundary_wse' and 'filename' keys.
    """
    def __init__(self, z, scenario_dir, manifest_rows, z_min, z_max, wse_min, wse_max, depth_min, depth_max, mask):
        self.z = z
        self.scenario_dir = scenario_dir
        self.rows = manifest_rows
        self.z_min, self.z_max = z_min, z_max
        self.wse_min, self.wse_max = wse_min, wse_max
        self.depth_min, self.depth_max = depth_min, depth_max
        self.mask = mask

    def __len__(self):
        """Number of scenarios in this split."""
        return len(self.rows)

    def __getitem__(self, i):
        """
        Build one (input, target) training pair for scenario i.

        Returns:
            input_tensor: shape (2, H, W) — elevation and broadcast
                boundary_wse stacked as channels.
            target_tensor: shape (1, H, W) — the true depth grid for this
                scenario's boundary_wse.
        """
        row = self.rows[i]
        boundary_wse = float(row['boundary_wse'])
        filename = row['filename']
        depth = np.load(Path(self.scenario_dir) / filename)

        norm_z = normalise(self.z, self.z_min, self.z_max)
        norm_depth = normalise(depth, self.depth_min, self.depth_max)
        norm_wse = normalise(boundary_wse, self.wse_min, self.wse_max)

        wse_channel = np.full_like(norm_z, norm_wse, dtype=np.float32)
        input_array = np.stack([norm_z, wse_channel], axis=0)  # shape (2, H, W)

        # elevaion and boundary wse, used for the model to make predictions:
        input_tensor = torch.from_numpy(input_array).float()
        # true depth grid, used to compare predictions against
        target_tensor = torch.from_numpy(norm_depth).float().unsqueeze(0)  # shape (1, H, W)

        return input_tensor, target_tensor


